/**
 * Maps BKR-star.ttl to four target representations by executing SPARQL CONSTRUCT queries.
 *
 * Outputs written to the same directory as this script:
 *   BKR-Graph.trig        — named-graph representation        (mapToGraph-Q1/Q2)
 *   BKR-Reification.ttl   — RDF 1.1 reification pattern       (mapToReification-Q1/Q2)
 *   BKR-Singleton.ttl     — singleton-property pattern         (mapToSingleton-Q1/Q2)
 *   BKR-WikiData.ttl      — Wikidata-style n-ary pattern       (mapToWikiData-Q1/Q2)
 *
 * Memory-efficient implementation: instead of loading the entire source file into an
 * in-memory N3.Store (Comunica's default), each SPARQL pattern match call streams the
 * file via N3.StreamParser. This keeps heap usage near-constant regardless of file size.
 *
 * Usage:
 *   npx tsx mapBkrStar.ts
 */

import { createReadStream, createWriteStream } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { Transform } from 'node:stream';
import { fileURLToPath } from 'node:url';
import { QueryEngine } from '@comunica/query-sparql-file';
import type * as RDF from '@rdfjs/types';
import { StreamParser, Writer } from 'n3';
import { DataFactory } from 'rdf-data-factory';
import { termToString } from 'rdf-string';

const __dirname = dirname(fileURLToPath(import.meta.url));

const DF = new DataFactory();
const engine = new QueryEngine();
const sourcePath = resolve(__dirname, 'BKR-star.ttl');

/**
 * A streaming RDF.js Source backed by an N3.StreamParser.
 *
 * Each call to `match()` opens a fresh read stream from the source file, parses it via
 * N3.StreamParser, and applies lightweight s/p/o/g filtering inline.  No in-memory
 * quad store is ever built, so heap usage is bounded by the working set of the query
 * engine's join operators rather than by the full size of BKR-star.ttl.
 *
 * Comunica's `ActorQuerySourceIdentifyRdfJs` (type = 'rdfjs') will call `match()` once
 * per BGP pattern and join / filter results itself.  For the single-pattern queries
 * (Q2 and Q1 of Reification / Singleton) this means exactly one file scan.  For the
 * two-pattern WikiData-Q1 join, Comunica builds a hash-table for the smaller side
 * (the rdf:reifies-filtered scan) and stream-probes with the larger side, keeping
 * peak memory proportional to the number of reification triples rather than the whole
 * dataset.
 *
 * **Blank-node stability across multiple `match()` calls**
 *
 * BKR-star.ttl uses the old RDF-star syntax `<< s p o >> predicate object`.  N3 v2
 * auto-converts this to two triples:
 *   `_:auto rdf:reifies <<( s p o )>>` and `_:auto predicate object`
 * where `_:auto` is a blank node generated by `DataFactory.blankNode()` (no name).
 * `rdf-data-factory` numbers these with a per-instance counter.  If we reuse the
 * same counter across parses, the blank node sequence is different each time.
 *
 * Fix: create a fresh `DataFactory` with an explicit, stable `blankNodePrefix`
 * ('bkr_') for every `match()` call.  Because each DataFactory starts its counter
 * at 0 and uses the same prefix, and because the file is always read in the same
 * sequential order, every parse produces the same counter sequence (bkr_0, bkr_1, …)
 * even if Comunica issues concurrent match() calls for multi-pattern joins.  Explicit
 * blank nodes from the source (via blankNodePrefix: '') are unaffected because they
 * are passed by name and skip the counter entirely.
 */
class StreamingTurtleSource {
  public readonly features = <const>{ quotedTripleFiltering: false };

  public constructor(private readonly filePath: string) {}

  public match(
    subject?: RDF.Term | null,
    predicate?: RDF.Term | null,
    object?: RDF.Term | null,
    graph?: RDF.Term | null,
  ): RDF.Stream<RDF.Quad> & NodeJS.EventEmitter {
    // Create a fresh DataFactory with an explicit stable blankNodePrefix for each
    // match() call.  This ensures that the implicit reifier blank nodes generated by
    // N3 v2 when converting `<< s p o >> pred obj` always start at bkr_0, bkr_1, …
    // regardless of how many match() calls have previously been made.  Because the
    // file is always read sequentially, every parse generates the same blank-node IDs
    // for the same file positions — even for concurrent match() calls in a join.
    const matchDF = new DataFactory({ blankNodePrefix: 'bkr_' });
    // BlankNodePrefix: '' ensures that explicit blank nodes (_:name) in the source
    // are passed to the DataFactory by name (factory.blankNode('name')), bypassing
    // the counter.  This keeps explicit blank nodes stable across parses.
    const parser = new StreamParser({ factory: matchDF, blankNodePrefix: '' });

    const fileStream = createReadStream(this.filePath);

    // Propagate file-read errors into the parser stream.
    fileStream.on('error', err => parser.emit('error', err));
    fileStream.pipe(parser);

    const hasConstraint = subject ?? predicate ?? object ?? graph;
    if (!hasConstraint) {
      return <RDF.Stream<RDF.Quad> & NodeJS.EventEmitter><unknown>parser;
    }

    // Inline filter: only emit quads that satisfy every non-null constraint.
    const filter = new Transform({
      objectMode: true,
      transform(quad: RDF.Quad, _enc, cb) {
        if (
          (!subject || quad.subject.equals(subject)) &&
          (!predicate || quad.predicate.equals(predicate)) &&
          (!object || quad.object.equals(object)) &&
          (!graph || quad.graph.equals(graph))
        ) {
          this.push(quad);
        }
        cb();
      },
    });

    parser.on('error', (err: Error) => filter.emit('error', err));
    parser.pipe(filter);
    return <RDF.Stream<RDF.Quad> & NodeJS.EventEmitter><unknown>filter;
  }
}

/**
 * Extension function `<internal://bnode>`.
 *
 * Given any number of RDF term arguments, returns a blank node that is:
 *  - the same blank node every time the identical combination of arguments is seen, and
 *  - a fresh blank node the first time a new combination is encountered.
 *
 * The cache is intentionally global so that a single blank node is produced per unique
 * argument combination across the entire mapping run.
 */
const bnodeCache = new Map<string, RDF.BlankNode>();
let bnodeCounter = 0;

function cachedBnode(args: RDF.Term[]): RDF.BlankNode {
  // Build a collision-resistant key from termType + value of each argument.
  const key = args.map(t => `${t.termType}\x00${termToString(t)}`).join('\x01');
  let bnode = bnodeCache.get(key);
  if (!bnode) {
    bnode = DF.blankNode(`b${bnodeCounter++}`);
    bnodeCache.set(key, bnode);
  }
  return bnode;
}

const extensionFunctions: Record<string, (args: RDF.Term[]) => Promise<RDF.Term>> = {
  'internal://bnode': async(args: RDF.Term[]): Promise<RDF.Term> => cachedBnode(args),
};

// ---------------------------------------------------------------------------

interface MappingSpec {
  name: string;
  queries: readonly string[];
  output: string;
  /** N3 Writer format string, e.g. 'text/turtle' or 'application/trig'. */
  format: string;
  context?: Record<string, unknown>;
}

const mappings: MappingSpec[] = [
  // {
  //   name: 'mapToGraph',
  //   queries: [ 'mapToGraph-Q1.rq', 'mapToGraph-Q2.rq' ],
  //   // Q1 places triples inside named graphs; TriG is required to represent them.
  //   output: 'BKR-Graph.trig',
  //   format: 'application/trig',
  // },
  {
    name: 'mapToReification',
    queries: [ 'mapToReification-Q1.rq', 'mapToReification-Q2.rq' ],
    output: 'BKR-Reification.ttl',
    format: 'text/turtle',
  },
  {
    name: 'mapToSingleton',
    queries: [ 'mapToSingleton-Q1.rq', 'mapToSingleton-Q2.rq' ],
    output: 'BKR-Singleton.ttl',
    format: 'text/turtle',
  },
  {
    name: 'mapToWikiData',
    queries: [ 'mapToWikiData-Q1.rq', 'mapToWikiData-Q2.rq' ],
    output: 'BKR-WikiData.ttl',
    format: 'text/turtle',
    // Provide the <internal://bnode> extension function used in mapToWikiData-Q1.rq.
    context: { extensionFunctions },
  },
];

// ---------------------------------------------------------------------------

async function executeMapping(spec: MappingSpec): Promise<void> {
  const { name, queries, output, format, context = {}} = spec;
  const outputPath = resolve(__dirname, output);
  const outStream = createWriteStream(outputPath);
  const writer = new Writer(outStream, { format });

  process.stdout.write(`[${name}] Starting → ${output}\n`);
  let totalQuads = 0;

  // A fresh streaming source is used for every query so each scan gets its own
  // file handle and parser — Comunica never sees a pre-built store.
  const rdfjsSource = new StreamingTurtleSource(sourcePath);

  for (const queryFile of queries) {
    const queryPath = resolve(__dirname, queryFile);
    const query = await readFile(queryPath, 'utf-8');
    process.stdout.write(`[${name}] Executing ${queryFile}...\n`);

    const quadStream = await engine.queryQuads(query, {
      sources: [{ type: 'rdfjs', value: rdfjsSource }],
      ...context,
    });

    // Consume the quad stream with backpressure: pause the source while the
    // underlying file-write stream is draining so quads don't pile up in memory.
    await new Promise<void>((res, rej) => {
      quadStream.on('error', rej);
      quadStream.on('data', (quad: RDF.Quad) => {
        writer.addQuad(quad);

        if (++totalQuads % 100_000 === 0) {
          process.stdout.write(`\r[${name}] ${totalQuads.toLocaleString()} quads written...`);
        }
      });
      quadStream.on('end', () => res());
    });
  }

  if (totalQuads >= 100_000) {
    process.stdout.write('\r');
  }

  await new Promise<void>((res, rej) => {
    writer.end(error => (error ? rej(error) : res()));
  });

  process.stdout.write(`[${name}] Done — ${totalQuads.toLocaleString()} quads → ${output}\n`);
}

// ---------------------------------------------------------------------------

for (const mapping of mappings) {
  await executeMapping(mapping);
}

process.stdout.write('All mappings complete.\n');
